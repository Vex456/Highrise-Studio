  // Parses raw YAML into structured fields
  void _parseYamlToFields(String yaml) {
    _originalRawYaml = yaml;
    _rawYamlController.text = yaml;

    // Port
    final portMatch = RegExp(r'port:\s*(\d+)').firstMatch(yaml);
    if (portMatch != null) {
      _serverPort = int.tryParse(portMatch.group(1) ?? '8000') ?? 8000;
    }

    // Admin password
    final pwdMatch = RegExp(r'admin_password:\s*["'']?([^"''\n\r]+)["'']?').firstMatch(yaml);
    if (pwdMatch != null) {
      _adminPassword = pwdMatch.group(1)?.trim() ?? '';
    }

    // Stream URL
    final streamMatch = RegExp(r'radio_stream_url:\s*["'']?([^"''\n\r]+)["'']?').firstMatch(yaml);
    if (streamMatch != null) {
      _radioStreamUrl = streamMatch.group(1)?.trim() ?? '';
    }

    // Mini-games toggles
    if (yaml.contains('police_and_thief: false')) _enablePolice = false;
    if (yaml.contains('word_chain: false')) _enableWordChain = false;
    if (yaml.contains('chaty_matchmaker: false')) _enableChaty = false;
  }

  // Generates clean formatted YAML from visual fields
  String _generateYamlFromFields() {
    final buffer = StringBuffer();
    buffer.writeln('# ================================================');
    buffer.writeln('# Highrise Studio Ecosystem Configuration');
    buffer.writeln('# Auto-generated by Highrise Studio Android App');
    buffer.writeln('# ================================================\n');

    buffer.writeln('server:');
    buffer.writeln('  port: $_serverPort');
    buffer.writeln('  admin_password: "$_adminPassword"');
    buffer.writeln('');

    buffer.writeln('bots:');
    for (var b in _botConfigs) {
      buffer.writeln('  - bot_num: ${b.botNum}');
      buffer.writeln('    name: "${b.name}"');
      buffer.writeln('    role: "${b.role}"');
      buffer.writeln('    enabled: ${b.enabled}');
      buffer.writeln('    room: "${b.room}"');
      if (b.token.isNotEmpty) {
        buffer.writeln('    token: "${b.token}"');
      }
    }
    buffer.writeln('');

    buffer.writeln('rooms:');
    for (var r in _roomConfigs) {
      buffer.writeln('  - id: "${r.id}"');
      buffer.writeln('    name: "${r.name}"');
      buffer.writeln('    enabled: ${r.enabled}');
      buffer.writeln('    active_bots: [${r.activeBots.join(', ')}]');
    }
    buffer.writeln('');

    buffer.writeln('features:');
    buffer.writeln('  police_and_thief: $_enablePolice');
    buffer.writeln('  word_chain: $_enableWordChain');
    buffer.writeln('  chaty_matchmaker: $_enableChaty');
    buffer.writeln('  radio_stream_url: "$_radioStreamUrl"');

    return buffer.toString();
  }

  Future<void> _fetchLogs({bool silent = false}) async {
    if (!silent) setState(() => _isLoadingLogs = true);
    try {
      final entries = await widget.apiService.getLogs(
        level: _selectedLevel == 'ALL' ? null : _selectedLevel,
      );
      if (mounted) {
        setState(() {
          _logs = entries;
          _isLoadingLogs = false;
        });
        if (_autoScrollLogs && _logScrollController.hasClients) {
          _logScrollController.jumpTo(_logScrollController.position.maxScrollExtent);
        }
      }
    } catch (_) {
      if (mounted && !silent) setState(() => _isLoadingLogs = false);
    }
  }

  Future<void> _loadConfig() async {
    setState(() => _isLoadingConfig = true);
    try {
      final cfg = await widget.apiService.getRawConfig();
      if (mounted) {
        setState(() {
          _parseYamlToFields(cfg);
          _isLoadingConfig = false;
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isLoadingConfig = false);
      }
    }
  }

  Future<void> _saveConfig() async {
    setState(() => _isSavingConfig = true);
    final contentToSave = _isVisualEditor ? _generateYamlFromFields() : _rawYamlController.text;
    try {
      final ok = await widget.apiService.saveRawConfig(contentToSave);
      if (mounted) {
        setState(() {
          _isSavingConfig = false;
          _originalRawYaml = contentToSave;
          _rawYamlController.text = contentToSave;
        });
        if (ok) {
          ScaffoldMessenger.of(context).showSnackBar(
            const SnackBar(
              content: Text('Configuration saved and applied to server!'),
              backgroundColor: StudioTheme.accentEmerald,
            ),
          );
        } else {
          ScaffoldMessenger.of(context).showSnackBar(
            const SnackBar(
              content: Text('Server rejected configuration update'),
              backgroundColor: StudioTheme.accentRed,
            ),
          );
        }
      }
    } catch (e) {
      if (mounted) {
        setState(() => _isSavingConfig = false);
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Error saving config: $e'),
            backgroundColor: StudioTheme.accentRed,
          ),
        );
      }
    }
  }

  void _confirmRestart({required bool hard}) {
    showDialog(
      context: context,
      builder: (ctx) => AlertDialog(
        backgroundColor: StudioTheme.surfaceDark,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
        title: Row(
          children: [
            Icon(Icons.warning_amber_rounded, color: hard ? StudioTheme.accentRed : StudioTheme.accentYellow),
            const SizedBox(width: 8),
            Text(hard ? 'Hard Restart Server?' : 'Soft Restart Bots?', style: const TextStyle(color: Colors.white)),
          ],
        ),
        content: Text(
          hard
              ? 'This will reboot the entire Wispbyte container process. All active bot rooms and games will momentarily disconnect.'
              : 'This will re-initialize bot instances and reload configuration without dropping the host container.',
          style: const TextStyle(color: StudioTheme.textMuted, fontSize: 13),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx),
            child: const Text('Cancel', style: TextStyle(color: StudioTheme.textMuted)),
          ),
          ElevatedButton(
            style: ElevatedButton.styleFrom(
              backgroundColor: hard ? StudioTheme.accentRed : StudioTheme.accentSky,
              foregroundColor: StudioTheme.bgDark,
            ),
            onPressed: () async {
              Navigator.pop(ctx);
              final ok = await widget.apiService.restartSystem(hard: hard);
              if (mounted) {
                ScaffoldMessenger.of(context).showSnackBar(
                  SnackBar(
                    content: Text(ok ? 'Restart signal dispatched' : 'Failed to send restart signal'),
                    backgroundColor: ok ? StudioTheme.accentEmerald : StudioTheme.accentRed,
                  ),
                );
              }
            },
            child: Text(hard ? 'Reboot Container' : 'Restart Bots', style: const TextStyle(fontWeight: FontWeight.bold)),
          ),
        ],
      ),
    );
  }

