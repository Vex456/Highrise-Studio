                        padding: const EdgeInsets.all(12),
                        itemCount: filteredLogs.length,
                        itemBuilder: (context, index) {
                          final log = filteredLogs[index];
                          final timeStr = DateFormat('HH:mm:ss').format(log.timestamp);
                          Color levelColor = StudioTheme.accentSky;
                          if (log.level == 'ERROR') levelColor = StudioTheme.accentRed;
                          if (log.level == 'WARN') levelColor = StudioTheme.accentYellow;
                          if (log.level == 'DEBUG') levelColor = StudioTheme.textMuted;

                          return Padding(
                            padding: const EdgeInsets.symmetric(vertical: 2),
                            child: Row(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                Text(
                                  '[$timeStr] ',
                                  style: const TextStyle(
                                    fontFamily: 'monospace',
                                    color: StudioTheme.textMuted,
                                    fontSize: 11,
                                  ),
                                ),
                                Container(
                                  width: 48,
                                  alignment: Alignment.centerLeft,
                                  child: Text(
                                    log.level,
                                    style: TextStyle(
                                      fontFamily: 'monospace',
                                      color: levelColor,
                                      fontWeight: FontWeight.bold,
                                      fontSize: 11,
                                    ),
                                  ),
                                ),
                                Expanded(
                                  child: Text(
                                    log.message,
                                    style: const TextStyle(
                                      fontFamily: 'monospace',
                                      color: Colors.white,
                                      fontSize: 11,
                                    ),
                                  ),
                                ),
                              ],
                            ),
                          );
                        },
                      ),
                    ),
        ),
      ],
    );
  }

