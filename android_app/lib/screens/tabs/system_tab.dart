  // --- TAB 1: Console View ---
  Widget _buildConsoleView() {
    final filteredLogs = _logs.where((l) {
      if (_logSearchQuery.isEmpty) return true;
      return l.message.toLowerCase().contains(_logSearchQuery.toLowerCase()) ||
          l.logger.toLowerCase().contains(_logSearchQuery.toLowerCase());
    }).toList();

    return Column(
      children: [
        // Filter and Search Toolbar
        Container(
          padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 8),
          color: StudioTheme.surfaceDark,
          child: Column(
            children: [
              Row(
                children: [
                  Expanded(
                    child: SingleChildScrollView(
                      scrollDirection: Axis.horizontal,
                      child: Row(
                        children: ['ALL', 'INFO', 'WARN', 'ERROR', 'DEBUG'].map((lvl) {
                          final isSelected = _selectedLevel == lvl;
                          return Padding(
                            padding: const EdgeInsets.only(right: 6),
                            child: FilterChip(
                              label: Text(lvl, style: TextStyle(fontSize: 11, color: isSelected ? Colors.black : Colors.white)),
                              selected: isSelected,
                              selectedColor: StudioTheme.accentSky,
                              backgroundColor: StudioTheme.cardDark,
                              showCheckmark: false,
                              padding: const EdgeInsets.symmetric(horizontal: 6),
                              onSelected: (_) {
                                setState(() => _selectedLevel = lvl);
                                _fetchLogs();
                              },
                            ),
                          );
                        }).toList(),
                      ),
                    ),
                  ),
                  IconButton(
                    icon: Icon(
                      _autoScrollLogs ? Icons.vertical_align_bottom : Icons.pause_circle_outline,
                      color: _autoScrollLogs ? StudioTheme.accentSky : StudioTheme.textMuted,
                      size: 20,
                    ),
                    onPressed: () => setState(() => _autoScrollLogs = !_autoScrollLogs),
                    tooltip: 'Auto-scroll to latest',
                  ),
                  IconButton(
                    icon: const Icon(Icons.refresh, color: StudioTheme.textMuted, size: 20),
                    onPressed: () => _fetchLogs(),
                    tooltip: 'Refresh logs',
                  ),
                ],
              ),
              const SizedBox(height: 6),
              SizedBox(
                height: 36,
                child: TextField(
                  controller: _searchController,
                  onChanged: (val) => setState(() => _logSearchQuery = val),
                  style: const TextStyle(color: Colors.white, fontSize: 13),
                  decoration: InputDecoration(
                    hintText: 'Filter log messages...',
                    hintStyle: const TextStyle(color: StudioTheme.textMuted, fontSize: 12),
                    prefixIcon: const Icon(Icons.search, color: StudioTheme.textMuted, size: 16),
                    suffixIcon: _logSearchQuery.isNotEmpty
                        ? IconButton(
                            icon: const Icon(Icons.clear, color: StudioTheme.textMuted, size: 16),
                            onPressed: () {
                              _searchController.clear();
                              setState(() => _logSearchQuery = '');
