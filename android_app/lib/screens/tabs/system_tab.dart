                      onTap: () {
                        if (_isVisualEditor) {
                          _rawYamlController.text = _generateYamlFromFields();
                          setState(() => _isVisualEditor = false);
                        }
                      },
                      child: Container(
                        padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 6),
                        decoration: BoxDecoration(
                          color: !_isVisualEditor ? StudioTheme.accentSky : Colors.transparent,
                          borderRadius: BorderRadius.circular(7),
                        ),
                        child: Row(
                          children: [
                            Icon(Icons.code_rounded, size: 14, color: !_isVisualEditor ? StudioTheme.bgDark : StudioTheme.textMuted),
                            const SizedBox(width: 4),
                            Text('Raw YAML', style: TextStyle(fontSize: 11, fontWeight: FontWeight.bold, color: !_isVisualEditor ? StudioTheme.bgDark : StudioTheme.textMuted)),
                          ],
                        ),
                      ),
                    ),
