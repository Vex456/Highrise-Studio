  late TabController _subTabController;
  
  // Logs State
  List<LogEntry> _logs = [];
  String _selectedLevel = 'ALL';
  String _logSearchQuery = '';
  bool _autoScrollLogs = true;
  bool _isLoadingLogs = true;
  Timer? _logTimer;
