class BotConfigItem {
  int botNum;
  String name;
  String role;
  bool enabled;
  String token;
  String room;

  BotConfigItem({
    required this.botNum,
    required this.name,
    required this.role,
    this.enabled = true,
    this.token = '',
    this.room = '',
  });
}

class RoomConfigItem {
  String id;
  String name;
  bool enabled;
  List<int> activeBots;

  RoomConfigItem({
    required this.id,
    required this.name,
    this.enabled = true,
    required this.activeBots,
  });
}

